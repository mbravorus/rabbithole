import fs from "node:fs/promises";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { ICON_SELECTIONS } from "../src/core/html/icon-selection.js";

const require = createRequire(import.meta.url);
const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputFile = path.join(rootDir, "src/core/html/ionicons5.generated.js");
const packageRoot = path.dirname(require.resolve("@iconify-json/ion/package.json"));
const packageMetadata = JSON.parse(await fs.readFile(path.join(packageRoot, "package.json"), "utf8"));
const iconSet = JSON.parse(await fs.readFile(path.join(packageRoot, "icons.json"), "utf8"));

const EXPECTED_PACKAGE_VERSION = "1.0.2";
const EXPECTED_VERSION = "5.5.4";
const OUTLINE_STROKE_WIDTH = 48;
const ICON_NAMES = Object.freeze([...new Set(Object.values(ICON_SELECTIONS))].sort());

if (packageMetadata.version !== EXPECTED_PACKAGE_VERSION || packageMetadata.iconSetVersion !== EXPECTED_VERSION) {
  throw new Error(
    `Expected @iconify-json/ion ${EXPECTED_PACKAGE_VERSION} with Ionicons ${EXPECTED_VERSION}, ` +
    `found ${packageMetadata.version} with Ionicons ${packageMetadata.iconSetVersion}`
  );
}
if (iconSet.width !== 512 || iconSet.height !== 512) {
  throw new Error(`Expected a 512×512 Ionicons coordinate system, found ${iconSet.width}×${iconSet.height}`);
}

const definitions = {};
for (const name of ICON_NAMES) {
  definitions[name] = normalizeIcon(iconSet.icons[name], name);
}

const generated = renderModule(definitions);
if (process.argv.includes("--check")) {
  const committed = await fs.readFile(outputFile, "utf8").catch(() => "");
  if (committed !== generated) {
    process.stderr.write("Ionicons data is stale. Run npm run generate:icons and commit the result.\n");
    process.exit(1);
  }
} else {
  await fs.writeFile(outputFile, generated, "utf8");
}

function normalizeIcon(icon, name) {
  if (!icon || typeof icon.body !== "string" || !icon.body) {
    throw new Error(`Missing Ionicon: ${name}`);
  }

  const body = icon.body
    .replaceAll(' fill="currentColor"', "")
    .replaceAll(' stroke="currentColor"', "")
    .replaceAll(' stroke-width="32"', ` stroke-width="${OUTLINE_STROKE_WIDTH}"`);

  if (/<(?:script|style)\b|(?:href|src)=|class=|<title>/i.test(body)) {
    throw new Error(`Unexpected content in normalized Ionicon: ${name}`);
  }

  return {
    attrs: 'viewBox="0 0 512 512" fill="currentColor" stroke="currentColor"',
    body,
  };
}

function renderModule(definitions) {
  const entries = Object.entries(definitions).map(([name, definition]) =>
    `  ${JSON.stringify(name)}: ${JSON.stringify(definition)},`
  ).join("\n");

  return `/* This file is generated by scripts/generate-ionicons.mjs. Do not edit.
 * Source: Ionicons 5.5.4 (MIT), with outline strokes normalized for Rabbithole.
 * Only the curated glyphs used by the product are included.
 */

export const IONICONS_5 = Object.freeze({
${entries}
});
`;
}
